// 저장 데이터 (play.html 이 쓰고, index.html '이어하기'가 읽음)
const WHATIF_SAVE_KEY = "whatif_save";

function readWhatifSave() {
  try {
    const save = JSON.parse(localStorage.getItem(WHATIF_SAVE_KEY));
    const game = gameById(save?.id);
    return game && Number.isFinite(save.savedAt) ? { id: game.id, savedAt: save.savedAt } : null;
  } catch {
    return null;
  }
}
